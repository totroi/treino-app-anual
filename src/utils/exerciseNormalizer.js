export const sortMonthsChronologically = (months) => {
  return [...months].sort((a, b) => {
    const idxA = MONTHS_ORDER.indexOf(a);
    const idxB = MONTHS_ORDER.indexOf(b);
    if (idxA === -1 && idxB === -1) return a.localeCompare(b, 'pt-BR');
    if (idxA === -1) return 1;
    if (idxB === -1) return -1;
    return idxA - idxB;
  });
};

